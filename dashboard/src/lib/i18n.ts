export const dictionaries: Record<Locale, Dict> = { fr, ar };

export function getDict(locale: Locale): Dict {
  return dictionaries[locale] ?? fr;
}

export function translate(locale: Locale, key: string): string {
  return dictionaries[locale]?.[key] ?? fr[key] ?? key;
}

export function translateEnum(locale: Locale, value: string | null | undefined): string {
  if (!value) return "—";
  const d = dictionaries[locale];
  if (d && value in d) return d[value];
  if (value in fr) return fr[value];
  return value;
}

export function dirFor(locale: Locale): "ltr" | "rtl" {
  return locale === "ar" ? "rtl" : "ltr";
}
